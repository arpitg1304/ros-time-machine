"""vlm: run a local VLM for semantic triggers, and benchmark any VLM endpoint.

    vlm doctor                       what this machine can run
    vlm recommend --write-watch-list watch_list.yaml
    vlm serve                        start the recommended model (llama.cpp)
    vlm bench --provider llamacpp --model qwen3-vl-4b-instruct
    vlm bench --provider gemini --model <model id>     # hosted, needs GEMINI_API_KEY
"""

