INSTALL_HINTS = {
    ('llamacpp', 'apple'): 'brew install llama.cpp',
    ('llamacpp', 'nvidia'): 'build with CUDA (github.com/ggml-org/llama.cpp) or use the '
                            'ghcr.io/ggml-org/llama.cpp:server-cuda container',
    ('llamacpp', 'jetson'): 'jetson-containers run $(autotag llama_cpp)  '
                            '(github.com/dusty-nv/jetson-containers)',
    ('llamacpp', 'cpu'): 'brew install llama.cpp, or a release build from '
                         'github.com/ggml-org/llama.cpp/releases',
    ('vllm', 'nvidia'): 'pip install vllm',
    ('vllm', 'jetson'): 'jetson-containers run $(autotag vllm)',
    ('vllm', 'apple'): 'not available on macOS (vLLM needs a CUDA GPU)',
    ('vllm', 'cpu'): 'needs a CUDA GPU',
    ('ollama', 'any'): 'https://ollama.com/download',
}


def install_hint(backend: str, kind: str) -> str:
    return INSTALL_HINTS.get((backend, kind)) or INSTALL_HINTS.get((backend, 'any')) or \
        f'install {backend}'


def _resolve(args):
    """Device, recommendation and the profile/backend the user asked for (or auto)."""
    device = detect()
    rec = recommend(device, args.prefer)
    profile = PROFILES[args.profile] if getattr(args, 'profile', 'auto') != 'auto' \
        else rec.profile
    backend = getattr(args, 'backend', None) or rec.backend
    if not profile.gguf_repo and backend == 'llamacpp':
        backend = 'vllm'
    return device, rec, profile, backend


def _plan(args, device, profile, backend):
    binary = backends.find_binary(backend)
    flags = backends.supported_flags(binary) if binary and backend == 'llamacpp' else None
    launch = backends.plan(profile, backend, args.host, args.port, args.alias,
                           gpu=device.kind != 'cpu', flags=flags, extra_args=args.extra)
    if binary:
        launch.server[0] = binary
    return launch, binary


def watch_list_yaml(endpoint: str, model: str, watcher: dict) -> str:
    doc = {'watcher': {
        'endpoint': endpoint,
        'model': model,
        'cameras': ['/camera/front/image_raw/compressed'],
        'sample_hz': watcher.get('sample_hz', 1.0),
        'context_frames': int(watcher.get('context_frames', 4)),
        'max_image_px': int(watcher.get('max_image_px', 640)),
        'state_topics': ['/joint_states'],
        'min_confidence': 0.6,
        'cooldown_s': 10,
        'events': [{'label': 'object_dropped',
                    'describe': 'An object falls out of the gripper or off the table.',
                    'profile': 'manipulation'}],
    }}
    return ('# Generated by `vlm recommend`. Edit cameras and events for your robot.\n'
            + yaml.safe_dump(doc, sort_keys=False))


def cmd_profiles(args) -> int:
    for p in PROFILES.values():
        print(f'{p.key:20} ~{p.memory_gb:>4.1f} GB  {p.license:26} {p.notes}')
    return 0


def cmd_doctor(args) -> int:
    device, rec, profile, backend = _resolve(args)
    print(f'Device   {device.describe()}')
    for key, value in device.details.items():
        print(f'         {key}: {value}')
    for name in backends.BACKENDS:
        binary = backends.find_binary(name)
        print(f'{name:9}{binary or "not installed (" + install_hint(name, device.kind) + ")"}')
    print(f'Suggest  {profile.key} on {backend} (vlm recommend for details)')
    return 0


def cmd_recommend(args) -> int:
    device, rec, profile, backend = _resolve(args)
    try:
        launch, binary = _plan(args, device, profile, backend)
    except backends.BackendError as e:
        print(f'error: {e}', file=sys.stderr)
        return 2
    if args.json:
        print(json.dumps({
            'device': device.__dict__, 'profile': profile.key, 'backend': backend,
            'endpoint': launch.endpoint, 'model': launch.model, 'command': launch.shell(),
            'watcher': rec.watcher, 'reasons': rec.reasons, 'warnings': rec.warnings,
        }, indent=2))
    else:
        print(f'Device   {device.describe()}')
        print(f'Model    {profile.key} ({profile.gguf_ref or profile.hf_model}, '
              f'~{profile.memory_gb:g} GB, {profile.license})')
        print(f'         {profile.notes}')
        print(f'Runtime  {backend}: '
              + (binary or f'not installed -> {install_hint(backend, device.kind)}'))
        for reason in rec.reasons:
            print(f'Why      {reason}')
        for warning in rec.warnings + launch.notes:
            print(f'Note     {warning}')
        print('\nStart it:\n  vlm serve' + ('' if args.profile == 'auto' else
                                              f' --profile {profile.key}'))
        print('  # or directly:\n  ' + launch.shell().replace('\n', '\n  '))
        print(f'\nBenchmark it:\n  vlm bench --endpoint {launch.endpoint} --model {launch.model}')
        print('\nWatch list settings:')
        print(f'  endpoint: {launch.endpoint}\n  model: {launch.model}')
        for key, value in rec.watcher.items():
            print(f'  {key}: {value:g}')
    if args.write_watch_list:
        with open(args.write_watch_list, 'w', encoding='utf-8') as f:
            f.write(watch_list_yaml(launch.endpoint, launch.model, rec.watcher))
        print(f'\nWrote {args.write_watch_list}')
    return 0


def cmd_serve(args) -> int:
    device, rec, profile, backend = _resolve(args)
    try:
        launch, binary = _plan(args, device, profile, backend)
    except backends.BackendError as e:
        print(f'error: {e}', file=sys.stderr)
        return 2
    if args.dry_run:
        print(launch.shell())
        return 0
    if not binary and not backends.endpoint_ready(launch.endpoint):
        print(f'error: {launch.server[0]} not found. Install: '
              f'{install_hint(backend, device.kind)}', file=sys.stderr)
        return 2

    server = backends.ManagedServer(launch, args.log)
    stop = threading.Event()
    for sig in (signal.SIGINT, signal.SIGTERM):
        signal.signal(sig, lambda *_: stop.set())
    try:
        server.start()
        if server.reused:
            print(f'Reusing the server already answering at {launch.endpoint}')
        else:
            print(f'Starting {profile.key} on {backend} (first start downloads the model)...')
        if not server.wait_ready(args.timeout):
            print(f'error: {launch.endpoint} did not come up'
                  + (f'; see {args.log}' if args.log else ''), file=sys.stderr)
            return 1
        print(f'Ready: endpoint {launch.endpoint}  model {launch.model}', flush=True)
        while not stop.is_set():
            if server.process is not None and server.process.poll() is not None:
                print('error: server exited', file=sys.stderr)
                return 1
            stop.wait(1.0)
        return 0
    finally:
        server.stop()


def cmd_bench(args) -> int:
    provider = PROVIDERS.get(args.provider) if args.provider else None
    endpoint = args.endpoint or (provider.endpoint if provider else None)
    if not endpoint:
        print('error: give --provider or --endpoint', file=sys.stderr)
        return 2
    model = args.model
    if not model:
        print('error: --model is required (the name the endpoint serves)', file=sys.stderr)
        return 2
    key_env = args.api_key_env or (provider.api_key_env if provider else '')
    api_key = os.environ.get(key_env, '') if key_env else ''
    if key_env and not api_key:
        print(f'error: set {key_env}', file=sys.stderr)
        return 2

    try:
        watch_list = load_watch_list(args.watch_list) if args.watch_list else None
    except WatchListError as e:
        print(f'error: {e}', file=sys.stderr)
        return 2
    overrides = {'image_detail': args.image_detail} if args.image_detail else {}
    if args.extra_body:
        overrides['extra_body'] = json.loads(args.extra_body)
    config = bench_config(model, endpoint, args.frames, args.image_px, watch_list, **overrides)
    try:
        images = bench_images(config, args.requests, args.images)
    except ValueError as e:
        print(f'error: {e}', file=sys.stderr)
        return 2
    if args.images:
        from rtm_watcher.images import compressed_to_jpeg
        images = [compressed_to_jpeg(img, args.image_px) or img for img in images]

    if not args.images and not HAVE_PIL:
        print('Note: Pillow is not installed, so every request reuses one tiny frame and the '
              'results will look faster than real cameras (pip install pillow, or '
              'sudo apt install python3-pil)', file=sys.stderr)

    host = urlparse(endpoint).hostname or endpoint
    if (provider and provider.remote) or not (
            host in ('localhost', '127.0.0.1', '::1') or host.endswith('.local')):
        print(f'Note: sending {"your" if args.images else "synthetic"} frames to {host}',
              file=sys.stderr)

    client = OpenAICompatibleClient(
        endpoint, model, api_key=api_key, timeout_s=args.timeout,
        max_tokens=config.max_tokens, temperature=config.temperature,
        extra_body=config.extra_body)

    def progress(i, status):
        if not args.json:
            print(f'  {"cold" if i == 0 else f"#{i}":>5}  {status}', flush=True)

    result = run_bench(config, client, images, args.requests, synthetic=not args.images,
                       progress=progress)
    advice = suggest(result, args.sample_hz, config.extra_body)
    if args.json:
        print(json.dumps({**{k: v for k, v in result.__dict__.items() if k != 'latencies'},
                          'p50': result.p50, 'p95': result.p95, 'max': result.max,
                          'valid_rate': result.valid_rate, 'suggest': advice}, indent=2))
        return 0 if result.latencies else 1

    print(f'\nEndpoint {endpoint}  model {model}')
    print(f'Request  {result.frames} frames x {result.image_px}px '
          f'(~{result.image_kb:.0f} KB each), '
          + ('synthetic static scene' if result.synthetic else f'images from {args.images}'))
    if not result.latencies:
        print('No successful requests:\n  ' + '\n  '.join(result.errors[:3]))
        return 1
    print(f'Cold     {result.cold_s:.2f} s' if result.cold_s is not None else 'Cold     failed')
    print(f'Warm     p50 {result.p50:.2f} s  p95 {result.p95:.2f} s  max {result.max:.2f} s  '
          f'({result.requests} requests, {len(result.errors)} errors)')
    print(f'JSON     {100 * result.valid_rate:.0f}% valid')
    if result.synthetic:
        print(f'Alarms   {result.detections} detection(s) on a scene where nothing happens')
    print('\nSuggested settings')
    print(f'  watch list:   sample_hz: {advice["sample_hz"]}   '
          f'request_timeout_s: {advice["request_timeout_s"]}')
    print(f'  time machine: global.max_trigger_latency: {advice["max_trigger_latency"]}')
    print('  ' + (f'Keeps up with {args.sample_hz:g} Hz sampling.' if advice['keeps_up'] else
                  f'Falls behind {args.sample_hz:g} Hz sampling.'))
    if advice['hints']:
        print('\nHints')
        for hint in advice['hints']:
            print(f'  - {hint}')
    extras = dict(config.extra_body)
    if extras or args.image_detail:
        print('\nKeep these in the watch list too:')
        if extras:
            print(f'  extra_body: {json.dumps(extras)}')
        if args.image_detail:
            print(f'  image_detail: {args.image_detail}')
    return 0


def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(
        prog='vlm', description=__doc__.split('\n\n')[0],
        formatter_class=argparse.RawDescriptionHelpFormatter, epilog=__doc__.split('\n\n')[1])
    sub = parser.add_subparsers(dest='command', required=True)

    def local(p):
        p.add_argument('--profile', default='auto', choices=['auto'] + list(PROFILES))
        p.add_argument('--prefer', default='balanced', choices=PREFERENCES)
        p.add_argument('--backend', choices=backends.BACKENDS)
        p.add_argument('--host', default='127.0.0.1')
        p.add_argument('--port', type=int, default=8000)
        p.add_argument('--alias', default='', help='model name to serve under (llama.cpp, vLLM)')

    p = sub.add_parser('profiles', help='list the curated models')
    p.set_defaults(func=cmd_profiles)

    p = sub.add_parser('doctor', help='detect hardware and installed runtimes')
    p.add_argument('--prefer', default='balanced', choices=PREFERENCES)
    p.set_defaults(func=cmd_doctor, profile='auto')

    p = sub.add_parser('recommend', help='model, runtime and watcher settings for this device')
    local(p)
    p.add_argument('--write-watch-list', metavar='FILE')
    p.add_argument('--json', action='store_true')
    p.set_defaults(func=cmd_recommend)

    p = sub.add_parser('serve', help='start a local OpenAI-compatible VLM server')
    local(p)
    p.add_argument('--timeout', type=float, default=1800, help='seconds to wait (incl. download)')
    p.add_argument('--log', help='write server output to this file')
    p.add_argument('--dry-run', action='store_true', help='print the command and exit')
    p.set_defaults(func=cmd_serve)

    p = sub.add_parser('bench', help='latency and output check with watcher-shaped requests')
    p.add_argument('--provider', choices=list(PROVIDERS))
    p.add_argument('--endpoint')
    p.add_argument('--model')
    p.add_argument('--api-key-env')
    p.add_argument('--frames', type=int, default=4, help='images per request')
    p.add_argument('--image-px', type=int, default=640)
    p.add_argument('--image-detail', choices=['low', 'high', 'auto'])
    p.add_argument('--extra-body', help='JSON merged into each request')
    p.add_argument('--requests', type=int, default=10)
    p.add_argument('--images', help='directory of your own .jpg frames')
    p.add_argument('--watch-list', help='use your events and prompt context')
    p.add_argument('--sample-hz', type=float, default=1.0)
    p.add_argument('--timeout', type=float, default=60.0)
    p.add_argument('--json', action='store_true')
    p.set_defaults(func=cmd_bench)
    return parser


def main(argv: Optional[List[str]] = None) -> int:
    argv = list(sys.argv[1:] if argv is None else argv)
    if '--ros-args' in argv:  # Appended by ros2 run / launch
        argv = argv[:argv.index('--ros-args')]
    extra: List[str] = []
    if '--' in argv:  # Everything after -- goes to the server
        extra = argv[argv.index('--') + 1:]
        argv = argv[:argv.index('--')]
    args = build_parser().parse_args(argv)
    args.extra = extra
    return args.func(args)


if __name__ == '__main__':
    sys.exit(main())
